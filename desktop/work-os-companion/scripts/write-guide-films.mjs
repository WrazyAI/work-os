/**
 * Generate `src/guideFilms.ts` from a completed shoot.
 *
 * The film list is derived, never hand-written: durations come from the encoded
 * files and chapter labels come from the shot list, so the modal cannot drift
 * out of step with what was actually filmed. Called by
 * `scripts/shoot-guide-films.mjs` at the end of a run, and usable on its own
 * against an existing manifest.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = resolve(HERE, "..");
const manifestPath = process.argv[2] ?? "/tmp/opencode/film-work/manifest.json";
const outPath = resolve(APP, "src/guideFilms.ts");

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const views = ["day", "tasks", "review", "insights", "settings", "admin_overview", "admin_people", "admin_tasks", "admin_review", "admin_insights", "admin_evidence", "admin_settings"];
const banner = `/*
 * Generated by scripts/shoot-guide-films.mjs — do not edit by hand.
 *
 * One clip per numbered step of each page guide, filmed from the real
 * companion and encoded into \`public/guides\`. Durations come from the encoded
 * files and chapter labels from the shot list, so this cannot drift from the
 * film.
 */`;

const lines = [];
lines.push(`import type { GuideView } from "./guideState";`);
lines.push("");
lines.push(`export interface GuideFilm {`);
lines.push(`  /** Video path, relative to the app's public root. */`);
lines.push(`  file: string;`);
lines.push(`  /** First-frame still, shown before playback and under reduced motion. */`);
lines.push(`  poster: string;`);
lines.push(`  /** Short label for the step this clip illustrates. */`);
lines.push(`  chapter: string;`);
lines.push(`  /** Exact encoded length in seconds. */`);
lines.push(`  seconds: number;`);
lines.push(`}`);
lines.push("");
lines.push(`export const GUIDE_FILMS: Record<GuideView, GuideFilm[]> = {`);
for (const view of views) {
  const clips = manifest.filter((item) => item.guide === view).sort((a, b) => Number(a.chapter) - Number(b.chapter));
  lines.push(`  ${view}: [`);
  for (const clip of clips) {
    lines.push(`    { file: "${clip.file}", poster: "${clip.poster}", chapter: ${JSON.stringify(clip.chapterTitle ?? "")}, seconds: ${clip.duration} },`);
  }
  lines.push(`  ],`);
}
lines.push(`};`);
lines.push("");
lines.push(`/** The clips a guide plays, one per numbered step. */`);
lines.push(`export function guideFilmsFor(view: GuideView): GuideFilm[] {`);
lines.push(`  return GUIDE_FILMS[view] ?? [];`);
lines.push(`}`);
lines.push("");
lines.push(banner);

writeFileSync(outPath, lines.join("\n"));
console.log(`wrote ${outPath} (${manifest.length} clips)`);
