import {
  ADMIN_AGENT_API_AGENT_PROMPT,
  ADMIN_AGENT_API_BASE_URL,
  ADMIN_AGENT_API_GUIDE_URL,
  ADMIN_AGENT_API_MCP_URL,
  ADMIN_AGENT_API_OPENAPI_URL,
} from "./agent-api-docs";
import {
  ADMIN_AGENT_API_AUTH,
  ADMIN_AGENT_API_ENDPOINTS,
  ADMIN_AGENT_API_ERROR_ENVELOPE,
  ADMIN_AGENT_API_ERRORS,
  ADMIN_AGENT_API_FIRST_CALL,
  ADMIN_AGENT_API_GROUPS,
  ADMIN_AGENT_API_MCP_RULE,
  ADMIN_AGENT_API_MCP_TOOLS,
  ADMIN_AGENT_API_RULES,
  ADMIN_AGENT_API_SCOPES,
  ADMIN_AGENT_API_TOKEN_STEPS,
  adminEndpointScopeLabel,
} from "./admin-agent-api-docs";

export function buildAdminAgentInstructions() {
  return [
    "# Work OS Administrator Agent API v1",
    "",
    `- REST base: ${ADMIN_AGENT_API_BASE_URL}`,
    `- Administrator guide: ${ADMIN_AGENT_API_GUIDE_URL}`,
    `- OpenAPI contract: ${ADMIN_AGENT_API_OPENAPI_URL}`,
    `- Setup prompt: ${ADMIN_AGENT_API_AGENT_PROMPT}`,
    "",
    "## Authentication and token setup",
    ...[...ADMIN_AGENT_API_AUTH, ...ADMIN_AGENT_API_TOKEN_STEPS].map((text) => `- ${text}`),
    "",
    "Verify the token and administrator identity first:",
    "```sh",
    ADMIN_AGENT_API_FIRST_CALL,
    "```",
    "",
    "## Scopes",
    ...ADMIN_AGENT_API_SCOPES.map(({ id, default: isDefault, purpose }) => `- \`${id}\` (${isDefault ? "default" : "opt-in"}): ${purpose}`),
    "",
    "## Preview, confirm, and limits",
    ...ADMIN_AGENT_API_RULES.map(({ text }) => `- ${text}`),
    "",
    "## REST endpoints",
    ...Object.entries(ADMIN_AGENT_API_GROUPS).flatMap(([group, title]) => [
      "",
      `### ${title}`,
      ...ADMIN_AGENT_API_ENDPOINTS.filter((endpoint) => endpoint.group === group)
        .map((endpoint) => `- \`${endpoint.method} ${endpoint.path}\` (${adminEndpointScopeLabel(endpoint)}): ${endpoint.purpose}`),
    ]),
    "",
    "## REST errors",
    `Error envelope: \`${ADMIN_AGENT_API_ERROR_ENVELOPE}\``,
    ...ADMIN_AGENT_API_ERRORS.map(({ status, code, action }) => `- ${status} \`${code}\`: ${action}`),
    "",
    "## MCP",
    ADMIN_AGENT_API_MCP_URL,
    ADMIN_AGENT_API_MCP_RULE,
    ...ADMIN_AGENT_API_MCP_TOOLS.map(({ name, scope, purpose }) => `- \`${name}\` (${scope}): ${purpose}`),
    "",
  ].join("\n");
}
